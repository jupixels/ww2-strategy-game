// Archives the game's simulation (js/core in index.html's load order + the map data) for the leaderboard verifier
// and stamps a build id over that code into js/core/build.js. Run it whenever js/core or data/ changes:
//   node functions/sync.js
// firebase deploy runs it automatically (predeploy in firebase.json). Commit js/core/build.js and functions/builds/
// with the change. The verifier keeps the last KEEP builds, so a game started before an update can still be posted.
const fs = require('fs'), path = require('path'), crypto = require('crypto'), zlib = require('zlib');
const ROOT = path.join(__dirname, '..'), OUT = path.join(__dirname, 'builds'), KEEP = 12;
const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const order = [...html.matchAll(/<script src="(js\/core\/[^"]+)"><\/script>/g)].map(m => m[1]).filter(f => f !== 'js/core/build.js');
const MAPS = { world:'data/map.js', europe:'data/map-europe.js' };
const read = f => fs.readFileSync(path.join(ROOT, f));
const sha = (...bufs) => { const h = crypto.createHash('sha1'); for (const b of bufs) h.update(b); return h.digest('hex').slice(0, 12); };
const build = sha(...[...order, MAPS.world, MAPS.europe].map(read));
fs.writeFileSync(path.join(ROOT, 'js/core/build.js'), `'use strict';\n// generated by functions/sync.js from the simulation code: games record it, the leaderboard verifier checks it\nconst GAME_BUILD = '${build}';\n`);
fs.mkdirSync(OUT, { recursive:true });
const idxF = path.join(OUT, 'index.json');
const idx = fs.existsSync(idxF) ? JSON.parse(fs.readFileSync(idxF, 'utf8')) : { builds:[] };
const strip = s => s.toString('utf8').replace(/^'use strict';/m, '');
const gz = (name, text) => { const f = path.join(OUT, name); if (!fs.existsSync(f)) fs.writeFileSync(f, zlib.gzipSync(text, { level:9 })); return name; };
if (!idx.builds.some(b => b.id === build)) {
  const core = ['js/core/build.js', ...order].map(f => strip(read(f))).join('\n;\n');
  const entry = { id:build, at:new Date().toISOString().slice(0, 10), core:gz(`core-${build}.js.gz`, core) };
  for (const k in MAPS) { const b = read(MAPS[k]); entry[k] = gz(`map-${k}-${sha(b)}.js.gz`, strip(b)); }
  idx.builds.unshift(entry);
}
idx.builds.sort((a, b) => (a.id === build ? -1 : b.id === build ? 1 : 0));
idx.builds = idx.builds.slice(0, KEEP);
const used = new Set(['index.json']); for (const b of idx.builds) for (const k of ['core', ...Object.keys(MAPS)]) used.add(b[k]);
for (const f of fs.readdirSync(OUT)) if (!used.has(f)) fs.rmSync(path.join(OUT, f));
fs.writeFileSync(idxF, JSON.stringify(idx, null, 1) + '\n');
fs.rmSync(path.join(__dirname, 'game'), { recursive:true, force:true });   // the old unarchived copy
console.log(`game build ${build} (${order.length} core files); verifier keeps ${idx.builds.length} build(s)`);
